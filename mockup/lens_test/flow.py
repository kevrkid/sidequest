    v,s=wait(pg, lambda v: sum(x.startswith("ES:") for x in v)>=5, 90)
    ok("live: lines translated over the picture", s is not None, f"{s}s {v}")
    pg.wait_for_timeout(600); pg.screenshot(path=O+"/2-live.png")
    ok("status says Live", "Live" in pg.inner_text(".lz-stat"))
    ok("aim frame hidden once translating", pg.evaluate("document.querySelector('.lz-aim').classList.contains('off')"))
    pg.click("[data-a=freeze]"); pg.wait_for_timeout(300)
    ok("freeze pauses the picture", pg.evaluate("document.querySelector('.lz video').paused"))
    t=time.time()
    while time.time()-t<40 and pg.evaluate("__lensReading=document.querySelector('.lz-stat').innerText.includes('Reading')||document.querySelector('.lz-stat').innerText.includes('Translating')"): pg.wait_for_timeout(250)
    v=shown(pg); ok("frozen: translations shown", sum(x.startswith("ES:") for x in v)>=5, str(v))
    pg.screenshot(path=O+"/3-frozen.png")
    first=pg.locator(".lz-box.on:not(.wait)").first; before=first.text_content(); first.click(); pg.wait_for_timeout(200)
    after=pg.locator(".lz-box.orig").first.text_content() if pg.locator(".lz-box.orig").count() else None
    ok("tap a translation shows the original", after is not None and not after.startswith("ES:"), f"{before!r} -> {after!r}")
    pg.locator(".lz-box.orig").first.click(); pg.wait_for_timeout(150)
